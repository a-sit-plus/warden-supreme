/**
 * The BouncyCastle instance backing ML-DSA on the JVM. It is used as a provider *instance*
 * and never added to the global JCA provider list.
 */
internal val wardenBouncyCastle: Provider by lazy { BouncyCastleProvider() }

/** JDK 17 re-encodes unknown-algorithm keys with NULL parameters; RFC 9881 requires them to be absent. */
private fun normalizeMlDsaSpki(der: ByteArray): ByteArray {
    val spki = runCatching { SubjectPublicKeyInfo.getInstance(der) }.getOrNull() ?: return der
    val alg = spki.algorithm
    if (alg.parameters !is ASN1Null) return der
    if (MlDsaParameterSet.entries.none { it.oid.toString() == alg.algorithm.id }) return der
    return SubjectPublicKeyInfo(AlgorithmIdentifier(alg.algorithm), spki.publicKeyData.octets).encoded
}

/** An ML-DSA private key held by a JCA provider (BouncyCastle), together with its public key. */
class MlDsaJcaPrivateKey(val jcaPrivateKey: JcaPrivateKey, override val publicKey: MlDsaPublicKey) : PrivateKey.WithPublicKey {
    override val sourceRepresentation = SourceRepresentationStorage()
    override fun toString() = "MlDsaJcaPrivateKey(${publicKey.parameterSet.jcaName})"

    companion object {
        /** Wraps a JCA ML-DSA key pair (e.g. generated by BouncyCastle). */
        fun of(keyPair: KeyPair) = MlDsaJcaPrivateKey(
            keyPair.private,
            keyPair.public.toPublicKey() as? MlDsaPublicKey
                ?: throw IllegalArgumentException("Not an ML-DSA key pair: ${keyPair.public.algorithm}")
        )

        /** Generates a fresh BouncyCastle ML-DSA key pair. */
        fun generate(parameterSet: MlDsaParameterSet = MlDsaParameterSet.ML_DSA_65) =
            of(KeyPairGenerator.getInstance(parameterSet.jcaName, wardenBouncyCastle).generateKeyPair())
    }
}

/** An in-memory/JKS ML-DSA signer backed by a JCA private key. */
class MlDsaJvmSigner internal constructor(
    privateKey: JcaPrivateKey,
    provider: JCAProviderRef,
    override val publicKey: MlDsaPublicKey,
) : SupremeEphemeralJvmSigner(privateKey, provider) {
    private val jcaPrivateKey = privateKey
    override val signatureAlgorithm: MlDsaSignatureAlgorithm = publicKey.signatureAlgorithm
    override fun parseFromJca(bytes: ByteArray): Signature = MlDsaSignature(bytes)

    @SecretExposure
    override suspend fun exportPrivateKey(): PrivateKey.WithPublicKey = MlDsaJcaPrivateKey(jcaPrivateKey, publicKey)
}

private class MlDsaJksSigner(
    privateKey: JcaPrivateKey,
    provider: JCAProviderRef,
    override val publicKey: MlDsaPublicKey,
    override val alias: String,
    override val attestation: SelfAttestation,
) : SupremeEphemeralJvmSigner(privateKey, provider), JKSSigner {
    private val jcaPrivateKey = privateKey
    override val signatureAlgorithm: MlDsaSignatureAlgorithm = publicKey.signatureAlgorithm
    override fun parseFromJca(bytes: ByteArray): Signature = MlDsaSignature(bytes)

    @SecretExposure
    override suspend fun exportPrivateKey(): PrivateKey.WithPublicKey = MlDsaJcaPrivateKey(jcaPrivateKey, publicKey)
}

private class MlDsaJvmVerifier(
    override val signatureAlgorithm: MlDsaSignatureAlgorithm,
    override val publicKey: MlDsaPublicKey,
    provider: JCAProviderRef,
) : SupremeJVMVerifier(signatureAlgorithm, publicKey, provider)

private fun requireMatching(algorithm: MlDsaSignatureAlgorithm, key: PublicKey): MlDsaPublicKey {
    require(key is MlDsaPublicKey) { "$algorithm requires an ML-DSA key, got ${key::class.simpleName}" }
    require(key.parameterSet == algorithm.parameterSet) {
        "$algorithm cannot be used with a ${key.parameterSet.jcaName} key"
    }
    return key
}

/** Verifies ML-DSA signatures through the JCA (BouncyCastle unless a provider is specified). */
internal object MlDsaJvmVerifierProvider : SignatureVerifierProvider {
    override fun verifierFor(algorithm: SignatureAlgorithm, key: PublicKey, config: VerifierConfiguration): SignatureVerifier? {
        if (algorithm !is MlDsaSignatureAlgorithm) return null
        return MlDsaJvmVerifier(algorithm, requireMatching(algorithm, key), config.jvm.v.provider)
    }
}

/** Creates signers for [MlDsaJcaPrivateKey]s: `MlDsaSignatureAlgorithm[set].signerFor(key)`. */
internal object MlDsaJvmInMemoryKeys : InMemoryKeysProvider {
    override suspend fun makeEphemeralSigner(config: EphemeralSignerConfiguration): Signer.WithExportableKey? = null

    override fun createSignerForKey(
        algorithm: SignatureAlgorithm,
        privateKey: PrivateKey.WithPublicKey,
        config: InMemorySignerConfiguration,
    ): Signer.WithExportableKey? {
        if (algorithm !is MlDsaSignatureAlgorithm || privateKey !is MlDsaJcaPrivateKey) return null
        return MlDsaJvmSigner(privateKey.jcaPrivateKey, config.jvm.v.provider, requireMatching(algorithm, privateKey.publicKey))
    }
}

/** Java key store support for `createSigningKey(alias) { mlDsa { } }` on the JVM. */
internal object MlDsaJksOperations : JavaKeyStoreOperationsProvider {
    override fun createKeyPair(config: JKSSigningKeyConfiguration): Pair<SignatureAlgorithm, KeyPair>? {
        val set = config.mlDsa.v?.parameterSet ?: return null
        val kpg = when (val ref = config.provider) {
            is JCAProviderRef.ByName -> KeyPairGenerator.getInstance(set.jcaName, ref.provider)
            is JCAProviderRefO -> KeyPairGenerator.getInstance(set.jcaName, ref.provider)
            else -> KeyPairGenerator.getInstance(set.jcaName, wardenBouncyCastle)
        }
        return MlDsaSignatureAlgorithm[set] to kpg.generateKeyPair()
    }

    override fun getJKSSigner(
        jcaPrivateKey: JcaPrivateKey,
        alias: String,
        config: JKSSignerConfiguration,
        attestation: SelfAttestation,
    ): JKSSigner? {
        val key = attestation.certificate.publicKey as? MlDsaPublicKey ?: return null
        return MlDsaJksSigner(jcaPrivateKey, config.provider, key, alias, attestation)
    }
}

internal actual fun installPlatformMlDsa() {
    ServiceLoader.register<JcaMappingProvider>(MlDsaJcaMapping(wardenBouncyCastle, ::normalizeMlDsaSpki))
    ServiceLoader.register<SignatureVerifierProvider>(MlDsaJvmVerifierProvider)
    ServiceLoader.register<InMemoryKeysProvider>(MlDsaJvmInMemoryKeys)
    ServiceLoader.register<JavaKeyStoreOperationsProvider>(MlDsaJksOperations)
}
